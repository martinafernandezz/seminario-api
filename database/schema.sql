--  olimpo (postgresql)
-- crear la base: createdb -U postgres olimpo
-- cargar: psql -U postgres -d olimpo -f database/schema.sql

DROP TABLE IF EXISTS pago, servicio, reserva, turno_fijo,
  precio, cancha, tipo_cancha, usuario CASCADE;
DROP FUNCTION IF EXISTS fn_pago_max2() CASCADE;

-- usuario
CREATE TABLE usuario (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre     VARCHAR(100) NOT NULL,
  apellido   VARCHAR(100) NOT NULL,
  dni        INTEGER      NOT NULL,
  username   VARCHAR(50)  NOT NULL,
  password   VARCHAR(255) NOT NULL,              -- hash bcrypt
  mail       VARCHAR(100) NOT NULL,
  telefono   BIGINT       NULL,
  rol        VARCHAR(20)  NOT NULL DEFAULT 'cliente',
  estado     VARCHAR(20)  NOT NULL DEFAULT 'activo',
  CONSTRAINT uk_usuario_dni      UNIQUE (dni),
  CONSTRAINT uk_usuario_username UNIQUE (username),
  CONSTRAINT uk_usuario_mail     UNIQUE (mail),
  CONSTRAINT ck_usuario_rol      CHECK (rol IN ('administrador', 'cliente')),
  CONSTRAINT ck_usuario_dni      CHECK (dni > 0),
  CONSTRAINT ck_usuario_telefono CHECK (telefono IS NULL OR telefono > 0)
);

-- tipo_cancha
CREATE TABLE tipo_cancha (
  id_tipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  VARCHAR(100) NOT NULL,
  deporte VARCHAR(50)  NOT NULL
);

-- cancha
CREATE TABLE cancha (
  id_cancha INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_tipo   INTEGER      NOT NULL,
  nombre    VARCHAR(100) NOT NULL,
  estado    VARCHAR(30)  NOT NULL DEFAULT 'disponible',
  CONSTRAINT fk_cancha_tipo FOREIGN KEY (id_tipo) REFERENCES tipo_cancha (id_tipo)
);
CREATE INDEX idx_cancha_tipo ON cancha (id_tipo);

-- precio, historial por cancha
CREATE TABLE precio (
  id_cancha       INTEGER       NOT NULL,
  fecha_vigencia  DATE          NOT NULL,
  precio_por_hora DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (id_cancha, fecha_vigencia),
  CONSTRAINT ck_precio_positivo CHECK (precio_por_hora >= 0),
  CONSTRAINT fk_precio_cancha FOREIGN KEY (id_cancha)
    REFERENCES cancha (id_cancha) ON DELETE CASCADE
);

-- turno_fijo
CREATE TABLE turno_fijo (
  id_turno_fijo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_desde   DATE NOT NULL,
  fecha_hasta   DATE NOT NULL,
  CONSTRAINT ck_turno_fijo_fechas CHECK (fecha_hasta >= fecha_desde)
);

-- reserva
CREATE TABLE reserva (
  id_reserva    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cancha     INTEGER       NOT NULL,
  id_usuario    INTEGER       NOT NULL,
  id_turno_fijo INTEGER       NULL,
  fecha         DATE          NOT NULL,
  hora_inicio   TIME          NOT NULL,
  hora_fin      TIME          NOT NULL,
  precio_total  DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  puntaje       INTEGER       NULL,
  resena        VARCHAR(500)  NULL,              -- reseña
  estado        VARCHAR(20)   NOT NULL DEFAULT 'pendiente',
  CONSTRAINT uk_reserva_turno   UNIQUE (id_cancha, fecha, hora_inicio),
  CONSTRAINT ck_reserva_horas   CHECK (hora_fin > hora_inicio),
  CONSTRAINT ck_reserva_puntaje CHECK (puntaje IS NULL OR puntaje BETWEEN 1 AND 5),
  CONSTRAINT ck_reserva_precio  CHECK (precio_total >= 0),
  CONSTRAINT fk_reserva_cancha  FOREIGN KEY (id_cancha)
    REFERENCES cancha (id_cancha),
  CONSTRAINT fk_reserva_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuario (id_usuario),
  CONSTRAINT fk_reserva_turno_fijo FOREIGN KEY (id_turno_fijo)
    REFERENCES turno_fijo (id_turno_fijo) ON DELETE SET NULL
);
CREATE INDEX idx_reserva_usuario    ON reserva (id_usuario);
CREATE INDEX idx_reserva_turno_fijo ON reserva (id_turno_fijo);
CREATE INDEX idx_reserva_fecha      ON reserva (fecha);

-- servicio, pertenece a una reserva como maximo
CREATE TABLE servicio (
  id_servicio     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva      INTEGER       NULL,
  nombre          VARCHAR(100)  NOT NULL,
  precio_servicio DECIMAL(10,2) NOT NULL,
  estado          BOOLEAN       NOT NULL DEFAULT TRUE,
  CONSTRAINT ck_servicio_precio CHECK (precio_servicio >= 0),
  CONSTRAINT fk_servicio_reserva FOREIGN KEY (id_reserva)
    REFERENCES reserva (id_reserva) ON DELETE SET NULL
);
CREATE INDEX idx_servicio_reserva ON servicio (id_reserva);

-- pago
CREATE TABLE pago (
  id_pago     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva  INTEGER       NOT NULL,
  monto       DECIMAL(10,2) NOT NULL,
  estado      VARCHAR(20)   NOT NULL DEFAULT 'pendiente',
  metodo_pago VARCHAR(30)   NOT NULL,
  fecha       DATE          NOT NULL DEFAULT CURRENT_DATE,
  sena        BOOLEAN       NOT NULL DEFAULT FALSE,   -- seña
  CONSTRAINT ck_pago_monto CHECK (monto > 0),
  CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva)
    REFERENCES reserva (id_reserva) ON DELETE CASCADE
);
CREATE INDEX idx_pago_reserva ON pago (id_reserva);

-- maximo 2 pagos por reserva
CREATE FUNCTION fn_pago_max2() RETURNS trigger AS $$
BEGIN
  IF (SELECT COUNT(*) FROM pago WHERE id_reserva = NEW.id_reserva) >= 2 THEN
    RAISE EXCEPTION 'Una reserva admite como maximo 2 pagos (sena + saldo)';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pago_max2 BEFORE INSERT ON pago
  FOR EACH ROW EXECUTE FUNCTION fn_pago_max2();
